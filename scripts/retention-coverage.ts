// node scripts/retention-coverage.ts — for every creature drawing, which of the ten cooking methods USDA's
// retention table has a factor for, through the family of the food the drawing wears. Pure: reads the
// drawings, the creature lists, the food pins and the table; writes docs/retention-coverage.md.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { retentionFamilyApplies } from "epistasis";
import { INGREDIENTS } from "../data/seed/ingredients.ts";
import { USDA_FOOD_PINS, type UsdaFoodPin } from "../lib/usda/foods.ts";
import { COOKING_METHODS, parseRetentionTable, retentionFamilyOf } from "../lib/usda/retention.ts";
import { RETENTION_TABLE } from "./seed/retention.ts";

type Creature = { key: string; fdcIds: number[] };
type Food = { usdaFdcId: number; category: string; usdaDescription: string };

const ART = "public/art/ingredients";
const CREATURES = "tools/art/creatures-sr-legacy.json";
const NAMED = "tools/art/creature-foods.json";
const OUT_DOC = "docs/retention-coverage.md";

const drawings = readdirSync(ART).filter((f) => f.endsWith(".svg")).map((f) => f.slice(0, -4)).sort();
const creatures = JSON.parse(readFileSync(CREATURES, "utf8")) as Creature[];
const named = JSON.parse(readFileSync(NAMED, "utf8")) as Record<string, number[]>;
const pins = JSON.parse(readFileSync(USDA_FOOD_PINS, "utf8")) as UsdaFoodPin[];
const foods = new Map<number, Food>([...pins, ...INGREDIENTS].map((f) => [f.usdaFdcId, f]));
const handPinned = new Map(INGREDIENTS.map((i) => [i.slug, i.usdaFdcId]));
const table = parseRetentionTable(readFileSync(RETENTION_TABLE, "utf8")).filter((r) => r.factor !== null);

/** The spellings a drawing's file may use for a creature key: the generator accepts a singular too. */
function variants(key: string): string[] {
  return [key, key.replace(/ies$/, "y"), key.replace(/ves$/, "f"), key.replace(/es$/, ""), key.replace(/s$/, "")];
}
const byVariant = new Map<string, Creature>();
for (const c of creatures) for (const v of variants(c.key)) if (!byVariant.has(v)) byVariant.set(v, c);

/** @return [Food | null] the first pinned food a drawing wears, the way the creature mapping resolves it */
function foodOf(key: string): Food | null {
  const fromList = byVariant.get(key)?.fdcIds.find((id) => foods.has(id));
  const id = fromList ?? handPinned.get(key) ?? named[key]?.find((n) => foods.has(n));
  return id === undefined ? null : foods.get(id)!;
}

function covered(family: string, method: string): boolean {
  return table.some((r) => retentionFamilyApplies(r.family, family) && r.prepMethods.includes(method));
}

const lines = drawings.map((key) => {
  const food = foodOf(key);
  const family = food ? retentionFamilyOf(food.category, food.usdaDescription, { fatPer100g: null }) : null;
  const withFactor = family === null ? [] : COOKING_METHODS.filter((m) => covered(family, m));
  const without = COOKING_METHODS.filter((m) => !withFactor.includes(m));
  return { key, food, family, withFactor, without };
});

const pairs = lines.length * COOKING_METHODS.length;
const have = lines.reduce((n, l) => n + l.withFactor.length, 0);
const noFamily = lines.filter((l) => l.family === null);
const noFood = noFamily.filter((l) => l.food === null);
const summary =
  `${lines.length} creatures × ${COOKING_METHODS.length} methods = ${pairs.toLocaleString("en-US")} pairs: ${have.toLocaleString("en-US")} have a retention factor, ` +
  `${(pairs - have).toLocaleString("en-US")} do not. ${noFamily.length} creatures have no family at all` +
  (noFood.length > 0 ? ` (${noFood.length} of them because no USDA food wears the drawing)` : "") +
  `, so none of their ${noFamily.length * COOKING_METHODS.length} pairs can.`;

if (!existsSync(OUT_DOC.split("/")[0])) throw new Error(`${OUT_DOC}: its folder is missing`);
writeFileSync(
  OUT_DOC,
  [
    "# Which cooking methods the retention table covers, creature by creature",
    "",
    `Generated by \`node scripts/retention-coverage.ts\` from the ${drawings.length} drawings in \`${ART}\`, the food each wears (its first pinned USDA food, as \`docs/creature-mapping.md\` resolves it), the family \`retentionFamilyOf\` gives that food with no fat hint, and USDA's Table of Nutrient Retention Factors, Release 6. A method has a factor when any row of the table for the family, or a family it descends from, names it for any nutrient.`,
    "",
    summary,
    "",
    "| Creature | Food | Family | Methods with a factor | Methods without |",
    "| --- | --- | --- | --- | --- |",
    ...lines.map((l) => `| ${l.key} | ${l.food ? `${l.food.usdaDescription} (${l.food.usdaFdcId})` : "no USDA food"} | ${l.family ?? "none"} | ${l.withFactor.join(", ") || "—"} | ${l.without.join(", ") || "—"} |`),
    "",
  ].join("\n"),
);
console.log(summary);
